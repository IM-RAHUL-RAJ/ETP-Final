// Writes src/environments/environment.ts from the repository's .env, so no address is hardcoded in
// the app. Runs automatically before start, build, watch and test (see the "pre*" scripts in package.json).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { authBase, frontendRoot, loadEnv, orderBase, required } from './env.mjs';

const env = loadEnv();
required(env, 'ORDER_SERVICE_URL', 'ORDER_SERVICE_PORT', 'AUTH_SERVICE_URL', 'AUTH_SERVICE_PORT');

const render = (production) => `// GENERATED by scripts/set-env.mjs from the repository's .env (see .env.example). Do not edit by hand.
export const environment = {
  production: ${production},
  tradeApiBase: '${orderBase(env)}',
  authApiBase: '${authBase(env)}'
};
`;

// environment.ts serves development and tests; environment.prod.ts replaces it in production builds (angular.json).
for (const [file, production] of [['environment.ts', false], ['environment.prod.ts', true]]) {
  const target = resolve(frontendRoot, 'src/environments', file);
  const content = render(production);
  if (!existsSync(target) || readFileSync(target, 'utf8') !== content) {
    writeFileSync(target, content);
    console.log(`${file} written: trade API ${orderBase(env)}, auth API ${authBase(env)}`);
  }
}
